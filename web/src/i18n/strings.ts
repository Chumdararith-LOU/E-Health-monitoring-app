const KH_DIGITS = ['០', '១', '២', '៣', '៤', '៥', '៦', '៧', '៨', '៩'];
const KM_MONTHS = ['មករា', 'កុម្ភៈ', 'មីនា', 'មេសា', 'ឧសភា', 'មិថុនា', 'កក្កដា', 'សីហា', 'កញ្ញា', 'តុលា', 'វិច្ឆិកា', 'ធ្នូ'];
const EN_MONTHS = ['Jan', 'Feb', 'Mar', 'Apr', 'May', 'Jun', 'Jul', 'Aug', 'Sep', 'Oct', 'Nov', 'Dec'];

/** Number + date formatting that follows the language and numeral setting (NFR-02). */
export function makeFormat(lang: 'km' | 'en', khmerDigits: boolean) {
  const n = (v: string | number) => {
    const s = String(v);
    return khmerDigits ? s.replace(/[0-9]/g, (d) => KH_DIGITS[Number(d)]) : s;
  };
  const two = (v: number) => String(v).padStart(2, '0');
  const month = (m: number) => (lang === 'km' ? KM_MONTHS[m] : EN_MONTHS[m]);
  return {
    n,
    day: (d: Date) => n(`${d.getDate()} ${month(d.getMonth())}`),
    dayY: (d: Date) => n(`${d.getDate()} ${month(d.getMonth())} ${d.getFullYear()}`),
    time: (d: Date) => n(`${two(d.getHours())}:${two(d.getMinutes())}`),
    dayTime: (d: Date) => n(`${d.getDate()} ${month(d.getMonth())} · ${two(d.getHours())}:${two(d.getMinutes())}`),
    iso: (d: Date) => `${d.getFullYear()}-${two(d.getMonth() + 1)}-${two(d.getDate())}`,
  };
}

